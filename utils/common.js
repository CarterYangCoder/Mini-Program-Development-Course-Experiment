const FAVORITES_KEY = 'favoriteNews'

function getNewsList() {
  return news.map(function (item) {
    return {
      id: item.id,
      poster: item.poster,
      add_date: item.add_date,
      title: item.title,
      category: item.category,
      source: item.source
    }
  })
}

function searchNews(keyword) {
  const words = (keyword || '').trim().toLowerCase().split(/\s+/).filter(function (w) { return w.length > 0 })
  if (words.length === 0) return getNewsList()
  return news.filter(function (item) {
    const haystack = (item.title + ' ' + item.content + ' ' + item.author + ' ' + item.source + ' ' + item.category).toLowerCase()
    return words.every(function (w) { return haystack.indexOf(w) >= 0 })
  }).map(function (item) {
    return {
      id: item.id,
      poster: item.poster,
      add_date: item.add_date,
      title: item.title,
      category: item.category,
      source: item.source
    }
  })
}

function getNewsDetail(newsID) {
  for (var i = 0; i < news.length; i++) {
    if (newsID === news[i].id) return { code: '200', news: news[i] }
  }
  return { code: '404', news: {} }
}

function getFavorites() {
  const favorites = wx.getStorageSync(FAVORITES_KEY)
  const list = Array.isArray(favorites) ? favorites : []
  const valid = list.filter(function (item) {
    return news.some(function (n) { return n.id === item.id })
  })
  if (valid.length !== list.length) wx.setStorageSync(FAVORITES_KEY, valid)
  return valid
}

function isFavorite(newsID) {
  return getFavorites().some(function (item) { return item.id === newsID })
}

function addFavorite(article) {
  const favorites = getFavorites()
  if (!isFavorite(article.id)) {
    favorites.unshift(article)
    wx.setStorageSync(FAVORITES_KEY, favorites)
  }
  return favorites
}

function removeFavorite(newsID) {
  const favorites = getFavorites().filter(function (item) { return item.id !== newsID })
  wx.setStorageSync(FAVORITES_KEY, favorites)
  return favorites
}

const HISTORY_KEY = 'searchHistory'

function getSearchHistory() {
  const history = wx.getStorageSync(HISTORY_KEY)
  return Array.isArray(history) ? history : []
}

function addSearchHistory(keyword) {
  const text = (keyword || '').trim()
  if (!text) return getSearchHistory()
  const history = getSearchHistory().filter(function (item) { return item !== text })
  history.unshift(text)
  if (history.length > 10) history.length = 10
  wx.setStorageSync(HISTORY_KEY, history)
  return history
}

function clearSearchHistory() {
  wx.removeStorageSync(HISTORY_KEY)
}

const INTERACTION_KEY = 'newsInteractions'

function readInteractions() {
  const data = wx.getStorageSync(INTERACTION_KEY)
  return data && typeof data === 'object' ? data : {}
}

function writeInteractions(data) {
  wx.setStorageSync(INTERACTION_KEY, data)
}

function getInteraction(newsID) {
  const local = readInteractions()[newsID] || {}
  return {
    liked: !!local.liked,
    likes: local.liked ? 1 : 0,
    favorites: isFavorite(newsID) ? 1 : 0,
    comments: Array.isArray(local.comments) ? local.comments : []
  }
}

function setLiked(newsID, liked) {
  const all = readInteractions()
  const local = all[newsID] || {}
  local.liked = liked
  all[newsID] = local
  writeInteractions(all)
  return getInteraction(newsID)
}

function addCommentRecord(newsID, comment) {
  const all = readInteractions()
  const local = all[newsID] || {}
  const comments = Array.isArray(local.comments) ? local.comments : []
  comments.unshift(comment)
  local.comments = comments
  all[newsID] = local
  writeInteractions(all)
  return comments
}

function updateComments(newsID, comments) {
  const all = readInteractions()
  const local = all[newsID] || {}
  local.comments = comments
  all[newsID] = local
  writeInteractions(all)
  return comments
}

function deleteCommentRecord(newsID, commentId) {
  const local = readInteractions()[newsID] || {}
  const comments = (Array.isArray(local.comments) ? local.comments : []).filter(function (c) {
    return c.id !== commentId
  })
  return updateComments(newsID, comments)
}

function toggleCommentLike(newsID, commentId) {
  const local = readInteractions()[newsID] || {}
  const comments = (Array.isArray(local.comments) ? local.comments : []).map(function (c) {
    if (c.id !== commentId) return c
    const copy = Object.assign({}, c)
    copy.likedByMe = !copy.likedByMe
    copy.likes = (copy.likes || 0) + (copy.likedByMe ? 1 : -1)
    return copy
  })
  return updateComments(newsID, comments)
}

function addReplyRecord(newsID, commentId, reply) {
  const local = readInteractions()[newsID] || {}
  const comments = (Array.isArray(local.comments) ? local.comments : []).map(function (c) {
    if (c.id !== commentId) return c
    const copy = Object.assign({}, c)
    const replies = Array.isArray(copy.replies) ? copy.replies.slice() : []
    replies.push(reply)
    copy.replies = replies
    return copy
  })
  return updateComments(newsID, comments)
}

function getInteractionTotals() {
  const all = readInteractions()
  let likes = 0
  let comments = 0
  Object.keys(all).forEach(function (newsID) {
    const local = all[newsID] || {}
    if (local.liked) likes++
    ;(Array.isArray(local.comments) ? local.comments : []).forEach(function (c) {
      comments++
      comments += Array.isArray(c.replies) ? c.replies.length : 0
      if (c.likedByMe) likes++
    })
  })
  return { likes: likes, comments: comments, favorites: getFavorites().length }
}

